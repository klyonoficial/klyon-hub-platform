-- MonthlySettlements: Fechamento mensal de repasses para parceiros
CREATE TABLE IF NOT EXISTS MonthlySettlements (
    Id INT NOT NULL AUTO_INCREMENT,
    CoworkingId INT NOT NULL COMMENT 'ID do parceiro',
    ReferenceMonth INT NOT NULL COMMENT 'Mês de referência (1-12)',
    ReferenceYear INT NOT NULL COMMENT 'Ano de referência',
    TotalAmount DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT 'Valor total a transferir para o parceiro',
    TotalGrossAmount DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT 'Valor bruto total das vendas',
    TotalPlatformCommission DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT 'Valor total da comissão da plataforma',
    CommissionCount INT NOT NULL DEFAULT 0 COMMENT 'Quantidade de comissões',
    Status VARCHAR(50) NOT NULL DEFAULT 'Open' COMMENT 'Status: Open, AwaitingInvoice, InvoiceReceived, InvoiceApproved, TransferScheduled, TransferProcessing, Completed, InvoiceRejected, TransferFailed, Cancelled',
    ClosedAt DATETIME(6) NULL COMMENT 'Data do fechamento',
    ScheduledTransferDate DATETIME(6) NULL COMMENT 'Data agendada para transferência',
    InvoiceDeadline DATETIME(6) NULL COMMENT 'Data limite para envio da NF',
    TransferredAt DATETIME(6) NULL COMMENT 'Data da transferência',
    ExternalTransferId VARCHAR(100) NULL COMMENT 'ID externo da transferência (PagBank)',
    PixKey VARCHAR(100) NULL COMMENT 'Chave PIX usada',
    FailureReason VARCHAR(2000) NULL COMMENT 'Motivo de falha',
    ApprovedBy INT NULL COMMENT 'ID do admin que aprovou',
    ApprovedAt DATETIME(6) NULL COMMENT 'Data da aprovação',
    Notes VARCHAR(2000) NULL COMMENT 'Observações',
    CreatedAt DATETIME(6) NOT NULL,
    UpdatedAt DATETIME(6) NULL,
    PRIMARY KEY (Id),
    CONSTRAINT FK_MonthlySettlements_Coworkings FOREIGN KEY (CoworkingId)
        REFERENCES Coworkings (Id) ON DELETE CASCADE,
    CONSTRAINT FK_MonthlySettlements_Users FOREIGN KEY (ApprovedBy)
        REFERENCES Users (Id) ON DELETE SET NULL,
    CONSTRAINT UQ_MonthlySettlements_Period UNIQUE (CoworkingId, ReferenceYear, ReferenceMonth)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Índices para MonthlySettlements
CREATE INDEX IX_MonthlySettlements_Status ON MonthlySettlements (Status);
CREATE INDEX IX_MonthlySettlements_ScheduledTransferDate ON MonthlySettlements (ScheduledTransferDate);
CREATE INDEX IX_MonthlySettlements_ExternalTransferId ON MonthlySettlements (ExternalTransferId);

-- SettlementCommissions: Relacionamento entre fechamento e comissões
CREATE TABLE IF NOT EXISTS SettlementCommissions (
    Id INT NOT NULL AUTO_INCREMENT,
    MonthlySettlementId INT NOT NULL COMMENT 'ID do fechamento',
    CommissionId INT NOT NULL COMMENT 'ID da comissão',
    Amount DECIMAL(10,2) NOT NULL COMMENT 'Valor da comissão no momento da inclusão',
    CreatedAt DATETIME(6) NOT NULL,
    PRIMARY KEY (Id),
    CONSTRAINT FK_SettlementCommissions_MonthlySettlements FOREIGN KEY (MonthlySettlementId)
        REFERENCES MonthlySettlements (Id) ON DELETE CASCADE,
    CONSTRAINT FK_SettlementCommissions_Commissions FOREIGN KEY (CommissionId)
        REFERENCES Commissions (Id) ON DELETE RESTRICT,
    CONSTRAINT UQ_SettlementCommissions_Unique UNIQUE (MonthlySettlementId, CommissionId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Índices para SettlementCommissions
CREATE INDEX IX_SettlementCommissions_CommissionId ON SettlementCommissions (CommissionId);

-- PartnerInvoices: Notas fiscais enviadas pelos parceiros
CREATE TABLE IF NOT EXISTS PartnerInvoices (
    Id INT NOT NULL AUTO_INCREMENT,
    MonthlySettlementId INT NOT NULL COMMENT 'ID do fechamento relacionado',
    CoworkingId INT NOT NULL COMMENT 'ID do parceiro',
    Type VARCHAR(50) NOT NULL DEFAULT 'ServiceInvoice' COMMENT 'Tipo: ServiceInvoice, AutoGenerated',
    Status VARCHAR(50) NOT NULL DEFAULT 'Pending' COMMENT 'Status: Pending, Submitted, AutoGenerated, Validating, Approved, Rejected, Expired',
    InvoiceAmount DECIMAL(12,2) NOT NULL COMMENT 'Valor declarado na NF',
    ExpectedAmount DECIMAL(12,2) NOT NULL COMMENT 'Valor esperado',
    InvoiceNumber VARCHAR(50) NULL COMMENT 'Número da NF',
    InvoiceSeries VARCHAR(10) NULL COMMENT 'Série da NF',
    IssueDate DATETIME(6) NULL COMMENT 'Data de emissão',
    IssuerCnpj VARCHAR(20) NULL COMMENT 'CNPJ do emitente',
    IssuerName VARCHAR(255) NULL COMMENT 'Razão social do emitente',
    AccessKey VARCHAR(50) NULL COMMENT 'Chave de acesso (NFe)',
    VerificationCode VARCHAR(50) NULL COMMENT 'Código de verificação (NFSe)',
    PdfFilePath VARCHAR(500) NULL COMMENT 'Caminho do PDF',
    XmlFilePath VARCHAR(500) NULL COMMENT 'Caminho do XML',
    XmlContent MEDIUMTEXT NULL COMMENT 'Conteúdo do XML',
    SubmittedAt DATETIME(6) NULL COMMENT 'Data do upload',
    Deadline DATETIME(6) NULL COMMENT 'Data limite',
    AutoValidationPassed TINYINT(1) NULL COMMENT 'Resultado validação automática',
    AutoValidationMessage VARCHAR(2000) NULL COMMENT 'Mensagem da validação',
    ValidatedBy INT NULL COMMENT 'ID do admin que validou',
    ValidatedAt DATETIME(6) NULL COMMENT 'Data da validação',
    RejectionReason VARCHAR(2000) NULL COMMENT 'Motivo da rejeição',
    IsAutoGenerated TINYINT(1) NOT NULL DEFAULT 0 COMMENT 'Se foi gerada automaticamente',
    FocusNFeRef VARCHAR(100) NULL COMMENT 'Referência no Focus NFe',
    PartnerNotes VARCHAR(2000) NULL COMMENT 'Observações do parceiro',
    AdminNotes VARCHAR(2000) NULL COMMENT 'Observações do admin',
    CreatedAt DATETIME(6) NOT NULL,
    UpdatedAt DATETIME(6) NULL,
    PRIMARY KEY (Id),
    CONSTRAINT FK_PartnerInvoices_MonthlySettlements FOREIGN KEY (MonthlySettlementId)
        REFERENCES MonthlySettlements (Id) ON DELETE CASCADE,
    CONSTRAINT FK_PartnerInvoices_Coworkings FOREIGN KEY (CoworkingId)
        REFERENCES Coworkings (Id) ON DELETE CASCADE,
    CONSTRAINT FK_PartnerInvoices_Users FOREIGN KEY (ValidatedBy)
        REFERENCES Users (Id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Índices para PartnerInvoices
CREATE INDEX IX_PartnerInvoices_MonthlySettlementId ON PartnerInvoices (MonthlySettlementId);
CREATE INDEX IX_PartnerInvoices_CoworkingId ON PartnerInvoices (CoworkingId);
CREATE INDEX IX_PartnerInvoices_Status ON PartnerInvoices (Status);

-- =============================================================================
-- Verificação
-- =============================================================================
SELECT 'MonthlySettlements' AS Tabela, COUNT(*) AS Total FROM MonthlySettlements
UNION ALL
SELECT 'SettlementCommissions', COUNT(*) FROM SettlementCommissions
UNION ALL
SELECT 'PartnerInvoices', COUNT(*) FROM PartnerInvoices;
