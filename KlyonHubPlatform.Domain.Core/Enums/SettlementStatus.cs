namespace KlyonHubPlatform.Domain.Core.Enums
{
    /// <summary>
    /// Status do fechamento mensal de repasses
    /// </summary>
    public enum SettlementStatus
    {
        /// <summary>Fechamento em aberto - ainda acumulando comissões do mês</summary>
        Open,

        /// <summary>Fechamento concluído - aguardando NF do parceiro</summary>
        AwaitingInvoice,

        /// <summary>NF recebida - aguardando validação do admin</summary>
        InvoiceReceived,

        /// <summary>NF aprovada - aguardando data do repasse</summary>
        InvoiceApproved,

        /// <summary>Repasse agendado - aguardando execução</summary>
        TransferScheduled,

        /// <summary>Transferência em processamento</summary>
        TransferProcessing,

        /// <summary>Transferência concluída com sucesso</summary>
        Completed,

        /// <summary>NF rejeitada - parceiro precisa enviar novamente</summary>
        InvoiceRejected,

        /// <summary>Transferência falhou</summary>
        TransferFailed,

        /// <summary>Cancelado</summary>
        Cancelled
    }

    /// <summary>
    /// Status de validação da nota fiscal do parceiro
    /// </summary>
    public enum InvoiceValidationStatus
    {
        /// <summary>Aguardando envio do parceiro</summary>
        Pending,

        /// <summary>NF enviada pelo parceiro - aguardando validação</summary>
        Submitted,

        /// <summary>NF emitida automaticamente pelo sistema</summary>
        AutoGenerated,

        /// <summary>NF em validação</summary>
        Validating,

        /// <summary>NF aprovada</summary>
        Approved,

        /// <summary>NF rejeitada</summary>
        Rejected,

        /// <summary>NF expirada (prazo de 5 dias úteis passou)</summary>
        Expired
    }

    /// <summary>
    /// Tipo de nota fiscal do parceiro
    /// </summary>
    public enum PartnerInvoiceType
    {
        /// <summary>NF de serviço emitida pelo parceiro para o cliente</summary>
        ServiceInvoice,

        /// <summary>NF emitida automaticamente pelo sistema via Focus NFe</summary>
        AutoGenerated
    }
}
