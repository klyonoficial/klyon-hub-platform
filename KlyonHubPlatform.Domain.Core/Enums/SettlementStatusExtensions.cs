using KlyonHubPlatform.Domain.Core.Constants;
namespace KlyonHubPlatform.Domain.Core.Enums
{
    public static class SettlementStatusExtensions
    {
        public static string ToBadgeCssClass(this SettlementStatus status) => status switch
        {
            SettlementStatus.Open => BootstrapBadgeCss.Secondary,
            SettlementStatus.AwaitingInvoice => BootstrapBadgeCss.Warning,
            SettlementStatus.InvoiceReceived => BootstrapBadgeCss.Info,
            SettlementStatus.InvoiceApproved => BootstrapBadgeCss.Primary,
            SettlementStatus.TransferScheduled => BootstrapBadgeCss.Primary,
            SettlementStatus.TransferProcessing => BootstrapBadgeCss.Info,
            SettlementStatus.Completed => BootstrapBadgeCss.Success,
            SettlementStatus.InvoiceRejected => BootstrapBadgeCss.Danger,
            SettlementStatus.TransferFailed => BootstrapBadgeCss.Danger,
            SettlementStatus.Cancelled => BootstrapBadgeCss.Secondary,
            _ => BootstrapBadgeCss.Secondary
        };
        public static string ToDisplayString(this SettlementStatus status) => status switch
        {
            SettlementStatus.Open => DisplayStrings.Open,
            SettlementStatus.AwaitingInvoice => DisplayStrings.AwaitingInvoice,
            SettlementStatus.InvoiceReceived => DisplayStrings.InvoiceReceived,
            SettlementStatus.InvoiceApproved => DisplayStrings.InvoiceApproved,
            SettlementStatus.TransferScheduled => DisplayStrings.TransferScheduled,
            SettlementStatus.TransferProcessing => DisplayStrings.TransferProcessing,
            SettlementStatus.Completed => DisplayStrings.Completed,
            SettlementStatus.InvoiceRejected => DisplayStrings.InvoiceRejected,
            SettlementStatus.TransferFailed => DisplayStrings.TransferFailed,
            SettlementStatus.Cancelled => DisplayStrings.Cancelled,
            _ => EnumDisplayConstants.Unknown
        };
        public static string ToDisplayString(this InvoiceValidationStatus status) => status switch
        {
            InvoiceValidationStatus.Pending => InvoiceDisplayStrings.Pending,
            InvoiceValidationStatus.Submitted => InvoiceDisplayStrings.Submitted,
            InvoiceValidationStatus.Approved => InvoiceDisplayStrings.Approved,
            InvoiceValidationStatus.Rejected => InvoiceDisplayStrings.Rejected,
            InvoiceValidationStatus.AutoGenerated => InvoiceDisplayStrings.AutoGenerated,
            InvoiceValidationStatus.Validating => InvoiceDisplayStrings.Validating,
            InvoiceValidationStatus.Expired => InvoiceDisplayStrings.Expired,
            _ => EnumDisplayConstants.Unknown
        };
        public static string ToBadgeCssClass(this InvoiceValidationStatus status) => status switch
        {
            InvoiceValidationStatus.Pending => BootstrapBadgeCss.Secondary,
            InvoiceValidationStatus.Submitted => BootstrapBadgeCss.Info,
            InvoiceValidationStatus.Approved => BootstrapBadgeCss.Success,
            InvoiceValidationStatus.Rejected => BootstrapBadgeCss.Danger,
            InvoiceValidationStatus.AutoGenerated => BootstrapBadgeCss.Warning,
            _ => BootstrapBadgeCss.Secondary
        };
        public static class DisplayStrings
        {
            public const string Open = "Em Aberto";
            public const string AwaitingInvoice = "Aguardando NF";
            public const string InvoiceReceived = "NF Recebida";
            public const string InvoiceApproved = "NF Aprovada";
            public const string TransferScheduled = "Agendado";
            public const string TransferProcessing = "Processando";
            public const string Completed = "Transferido";
            public const string InvoiceRejected = "NF Rejeitada";
            public const string TransferFailed = "Falha";
            public const string Cancelled = "Cancelado";
        }
        public static class InvoiceDisplayStrings
        {
            public const string Pending = "Pendente";
            public const string Submitted = "Enviada";
            public const string Approved = "Aprovada";
            public const string Rejected = "Rejeitada";
            public const string AutoGenerated = "Auto-gerada";
            public const string Validating = "Em validação";
            public const string Expired = "Expirada";
        }
    }
}