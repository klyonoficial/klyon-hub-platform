using KlyonHubPlatform.Domain.Core.Enums;

namespace KlyonHubPlatform.Domain.Entities
{
    /// <summary>
    /// Nota fiscal enviada pelo parceiro para validação
    /// Ou gerada automaticamente pelo sistema via Focus NFe
    /// </summary>
    public class PartnerInvoice
    {
        public int Id { get; set; }

        /// <summary>ID do fechamento mensal relacionado</summary>
        public int MonthlySettlementId { get; set; }

        /// <summary>ID do parceiro (coworking)</summary>
        public int CoworkingId { get; set; }

        /// <summary>Tipo da NF</summary>
        public PartnerInvoiceType Type { get; set; } = PartnerInvoiceType.ServiceInvoice;

        /// <summary>Status de validação</summary>
        public InvoiceValidationStatus Status { get; set; } = InvoiceValidationStatus.Pending;

        /// <summary>Valor declarado na NF</summary>
        public decimal InvoiceAmount { get; set; }

        /// <summary>Valor esperado (do fechamento)</summary>
        public decimal ExpectedAmount { get; set; }

        /// <summary>Número da NF</summary>
        public string? InvoiceNumber { get; set; }

        /// <summary>Série da NF</summary>
        public string? InvoiceSeries { get; set; }

        /// <summary>Data de emissão da NF</summary>
        public DateTime? IssueDate { get; set; }

        /// <summary>CNPJ do emitente</summary>
        public string? IssuerCnpj { get; set; }

        /// <summary>Razão social do emitente</summary>
        public string? IssuerName { get; set; }

        /// <summary>Chave de acesso da NF (se NFe)</summary>
        public string? AccessKey { get; set; }

        /// <summary>Código de verificação (se NFSe)</summary>
        public string? VerificationCode { get; set; }

        /// <summary>Caminho do arquivo PDF da NF</summary>
        public string? PdfFilePath { get; set; }

        /// <summary>Caminho do arquivo XML da NF</summary>
        public string? XmlFilePath { get; set; }

        /// <summary>Conteúdo do XML (para validação automática)</summary>
        public string? XmlContent { get; set; }

        /// <summary>Data do upload pelo parceiro</summary>
        public DateTime? SubmittedAt { get; set; }

        /// <summary>Data limite para envio</summary>
        public DateTime? Deadline { get; set; }

        /// <summary>Resultado da validação automática</summary>
        public bool? AutoValidationPassed { get; set; }

        /// <summary>Mensagem da validação automática</summary>
        public string? AutoValidationMessage { get; set; }

        /// <summary>ID do admin que validou</summary>
        public int? ValidatedBy { get; set; }

        /// <summary>Data da validação manual</summary>
        public DateTime? ValidatedAt { get; set; }

        /// <summary>Motivo da rejeição (se rejeitada)</summary>
        public string? RejectionReason { get; set; }

        /// <summary>Se foi gerada automaticamente via Focus NFe</summary>
        public bool IsAutoGenerated { get; set; } = false;

        /// <summary>ID de referência no Focus NFe (se auto gerada)</summary>
        public string? FocusNFeRef { get; set; }

        /// <summary>Observações do parceiro</summary>
        public string? PartnerNotes { get; set; }

        /// <summary>Observações do admin</summary>
        public string? AdminNotes { get; set; }

        public DateTime CreatedAt { get; set; }
        public DateTime? UpdatedAt { get; set; }

        // Navigation properties
        public virtual MonthlySettlement MonthlySettlement { get; set; } = null!;
        public virtual Coworking Coworking { get; set; } = null!;
        public virtual User? Validator { get; set; }
    }
}
